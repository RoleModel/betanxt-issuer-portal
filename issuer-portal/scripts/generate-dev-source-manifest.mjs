// @ts-nocheck
/**
 * Build-time generator for the developer-overlay source manifest.
 *
 * The overlay's `/api/dev/source` route lets a developer click a rendered
 * component and read the code that produced it. Locally that route reads the
 * working tree directly. On a deployment there is no working tree — and the
 * remote developers this tool exists for never clone the repo — so the source
 * has to travel *with the build*.
 *
 * This script snapshots every inspectable source file into a generated TypeScript
 * module that the route imports. Because the snapshot is imported, it is bundled
 * into the serverless function: the route serves the code from the code, never
 * from a file system the deployment does not have.
 *
 * Runs on `postinstall`, `predev`, and `prebuild`, and writes an ignored file,
 * so it never shows up as churn in a pull request.
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const scriptDir = import.meta.dirname;
const appRoot = path.resolve(scriptDir, "..");
const outputPath = path.join(
  appRoot,
  "app",
  "api",
  "dev",
  "source",
  "source-manifest.generated.ts"
);

// Keep in lockstep with SEARCH_ROOTS in app/api/dev/source/route.ts.
const SEARCH_ROOTS = ["components", "app", "contexts", "hooks", "utils", "lib"];
const SOURCE_EXTENSIONS = new Set([".ts", ".tsx"]);
const SKIP_DIRECTORIES = new Set(["node_modules", ".next", ".turbo", "dist"]);

// Do not snapshot the generated file into itself.
const SELF_RELATIVE = path
  .relative(appRoot, outputPath)
  .split(path.sep)
  .join("/");

const walk = async (directory) => {
  let entries;

  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch {
    // A root that isn't present in this workspace is not an error.
    return [];
  }

  const nested = await Promise.all(
    entries.map(async (entry) => {
      const entryPath = path.join(directory, entry.name);

      if (entry.isDirectory()) {
        return SKIP_DIRECTORIES.has(entry.name) ? [] : walk(entryPath);
      }

      return SOURCE_EXTENSIONS.has(path.extname(entry.name)) ? [entryPath] : [];
    })
  );

  return nested.flat();
};

const buildManifest = async () => {
  const roots = await Promise.all(
    SEARCH_ROOTS.map((directory) => walk(path.join(appRoot, directory)))
  );
  const files = roots.flat().sort();

  /** @type {Record<string, string>} */
  const manifest = {};

  await Promise.all(
    files.map(async (filePath) => {
      const relative = path
        .relative(appRoot, filePath)
        .split(path.sep)
        .join("/");

      if (relative === SELF_RELATIVE) {
        return;
      }

      manifest[relative] = await readFile(filePath, "utf8");
    })
  );

  return manifest;
};

const main = async () => {
  const manifest = await buildManifest();
  const fileCount = Object.keys(manifest).length;

  const contents = `// AUTO-GENERATED by scripts/generate-dev-source-manifest.mjs — do not edit.
// Snapshot of inspectable source for the developer overlay's /api/dev/source
// route so it can serve code from deployments that have no working tree.
// Regenerated on postinstall/predev/prebuild.

/** Repo-relative source path -> file contents, captured at build time. */
export const sourceManifest: Record<string, string> = ${JSON.stringify(manifest)};
`;

  await writeFile(outputPath, contents, "utf8");

  console.log(`Generated dev source manifest: ${fileCount} files`);
};

main().catch((error) => {
  console.error("Failed to generate dev source manifest:", error);
  process.exitCode = 1;
});
